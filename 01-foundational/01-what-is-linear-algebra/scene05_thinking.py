from manim import *
from common.mobjects import mach_stick_figure, thought_bubble
from common.palette import GOLD_LIGHT, STONE_AXIS, COPPER_TERRA
from common.latex import mach_math_template


def play_scene05(scene):

    # ==============================================================
    # 1. شخصية التفكير (العين والتنفس يعملان تلقائياً بأمان 100%)
    # ==============================================================

    thinker = mach_stick_figure(
        color=STONE_AXIS,
        pose="thinking",
        scale=1.0,
        blink=True,
        breathing=True,
    ).shift(LEFT * 0.9)

    # ==============================================================
    # 2. بالونة التفكير
    # ==============================================================

    box, dots, mark = thought_bubble(
        text=r"! \ ?",
        anchor_head=thinker[0],
        color=GOLD_LIGHT,
        text_color=COPPER_TERRA,
        tex_template=mach_math_template,
    )

    scene_group = VGroup(
        thinker,
        box,
        dots,
        mark,
    )

    # ==============================================================
    # 3. ظهور الشخصية (0.8 ثانية)
    # يبدأ عند 01:29 في الفيديو مع بداية صوتك
    # ==============================================================

    scene.play(
        FadeIn(
            thinker,
            shift=UP * 0.2,
        ),
        run_time=0.8,
    )

    # ==============================================================
    # 4. ظهور بالونة التفكير (1.0 ثانية)
    # ==============================================================

    scene.play(
        FadeIn(
            dots,
            scale=0.5,
        ),
        FadeIn(
            box,
            scale=0.9,
        ),
        Write(mark),
        run_time=1.0,
    )

    # ==============================================================
    # 5. فترة التفكير والشرح الصوتي المستمر (36.4 ثانية مضبوطة على صوتك)
    # ==============================================================

    # أ) "لو بصيت للإجابتين بتوع سؤال علم الحساب وسؤال علم التفاضل والتكامل،
    #     هتحس إن الإجابتين فيهم حاجة شبه بعض..." (5.0s)
    scene.wait(5.0)

    # ب) "في الحساب مثلاً أنت بتتعامل مع أرقام وبتنفذ عليها قواعد
    #     وعمليات حسابية محددة زي الجمع والضرب..." (8.0s)
    scene.wait(8.0)

    # ج) "وفي التفاضل والتكامل أنت بتتعامل مع دوال وبرضو بتنفذ عليها قواعد
    #     وعمليات حسابية محددة زي عملية التفاضل وعملية التكامل..." (9.0s)
    scene.wait(9.0)

    # د) "واللي درس التفاضل والتكامل متعدد المتغيرات (multivariable calculus)
    #     هيقولك إن فيه عمليات تانية غير التفاضل والتكامل...
    #     بس يكفيني إنك تكون عارف حالياً التفاضل والتكامل اللي معظمنا درسه في الثانوية أو في الجامعة." (14.4s)
    scene.wait(14.4)

    # ==============================================================
    # 6. تفريغ المشهد (1.8 ثانية)
    # ==============================================================

    scene.play(
        FadeOut(scene_group),
        run_time=0.8,
    )

    # استقرار الغرفة قبل كروت المقارنة في المشهد السادس
    scene.wait(1.0)

    # الحسبة الإجمالية للمشهد الخامس:
    # 0.8 + 1.0 + 36.4 + 0.8 + 1.0 = 40.0 ثانية بالتمام والكمال!