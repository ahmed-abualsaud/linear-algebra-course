from manim import *
from common.portal import MachPortal
from common.identity import turn_on_neon
from common.palette import GOLD_LIGHT, IVORY_WHITE


def play_scene01(scene):
    portal = MachPortal(scene)

    # 1. علامة الاستفهام
    q_mark = Text(
        "?", font="Cairo", weight=BOLD, font_size=150, color=GOLD_LIGHT
    ).shift(UP * 0.6)

    # 2. نص السؤال
    question_text = Text(
        "إيه هو الجبر الخطي؟",
        font="Cairo",
        weight=BOLD,
        font_size=42,
        color=IVORY_WHITE,
    ).next_to(q_mark, DOWN, buff=0.6)

    # ==============================================================
    # 1. إشعال النيون ودخول السؤال (3.2 ثوانٍ)
    # الكلام: "أنا عايز أطرح سؤال وهو باين جداً من عنوان الحلقة..."
    # ==============================================================
    turn_on_neon(scene, run_time=1.0)

    # علامة الاستفهام تخترق الجدار الأيمن
    portal.enter(q_mark, direction=RIGHT, run_time=1.2)

    # نص السؤال يصعد من الأرضية ليستقر في مكانه
    portal.enter(question_text, direction=DOWN, distance=3.0, run_time=1.0)

    # ==============================================================
    # 2. وقفة نطق السؤال الرئيسي (1.8 ثانية)
    # الكلام: "... إيه هو الجبر الخطي؟"
    # ==============================================================
    scene.wait(1.8)

    # ==============================================================
    # 3. عرض السؤال وثباته أثناء الشرح والتمهيد (14.2 ثانية)
    # الكلام:
    # "السؤال ده عامل بالظبط كأنك بتسأل عن إيه هو علم الحساب،
    # أو إيه هو التفاضل والتكامل (calculus)...
    # لكن معلش خلينا ننسى الجبر الخطي دلوقتي وناخد علم الحساب كمثال
    # لأن كل البشر تقريباً عارفين إزاي يحسبوا."
    # ==============================================================
    scene.wait(14.2)

    # ==============================================================
    # 4. خروج السؤال وتفريغ الشاشة لعلم الحساب (2.8 ثانية)
    # التزامن: يختفيان مع نهاية جملة "... عارفين إزاي يحسبوا"
    # ==============================================================
    portal.exit(q_mark, direction=LEFT, run_time=0.9)
    portal.exit(question_text, direction=DOWN, run_time=0.9)

    # سكون الغرفة لثانية واحدة استعداداً للمشهد الثاني
    scene.wait(1.0)

    # الحسبة الإجمالية للمشهد الأول:
    # 1.0 (نيون) + 1.2 (دخول علامة الاستفهام) + 1.0 (دخول النص) + 1.8 (نطق السؤال)
    # + 14.2 (شرح المقارنة) + 0.9 (خروج الاستفهام) + 0.9 (خروج النص) + 1.0 (استقرار)
    # = 22.0 ثانية بالضبط!