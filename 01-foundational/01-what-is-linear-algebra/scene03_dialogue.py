from manim import *
from common.mobjects import mach_stick_figure, speech_bubble
from common.palette import GOLD_LIGHT, STONE_AXIS


def play_scene03(scene):

    # ==============================================================
    # 1. الشخصيتان في مواضعهما المرفوعة للأعلى (لترك مساحة للترجمة)
    # تم التعديل من DOWN * 0.9 إلى DOWN * 0.55 بأمان تام
    # ==============================================================

    person_right = mach_stick_figure(
        color=STONE_AXIS,
        pose="neutral",
        scale=0.9,
        blink=True,
    ).shift(RIGHT * 1.5 + DOWN * 0.55)

    person_left = mach_stick_figure(
        color=GOLD_LIGHT,
        pose="neutral",
        scale=0.9,
        blink=True,
    ).shift(LEFT * 1.5 + DOWN * 0.55)

    # ==============================================================
    # 2. بالونة السؤال - اليمين (نفس الكود الأصلي)
    # ==============================================================

    box_r, dots_r, text_r = speech_bubble(
        lines_text=[
            "طيب إيه هو",
            "التفاضل والتكامل؟",
        ],
        anchor_head=person_right[0],
        color=STONE_AXIS,
        font_size=23,
        shift=RIGHT * 0.85,
    )

    # ==============================================================
    # 3. بالونة الإجابة - اليسار (نفس الكود الأصلي)
    # ==============================================================

    box_l, dots_l, text_l = speech_bubble(
        lines_text=[
            "إحنا بندرس في التفاضل والتكامل",
            "حاجة اسمها الدوال، وبنطبق عليها",
            "عملية اسمها التفاضل وعملية تانية",
            "اسمها التكامل",
        ],
        anchor_head=person_left[0],
        color=GOLD_LIGHT,
        font_size=19,
        shift=LEFT * 0.85,
    )

    # ==============================================================
    # 4. ظهور الشخصيتين والتنفس (زمن أصلي 100% = 1.3 ثانية)
    # الكلام:
    # "ونفس الكلام لو سألت حد درس علم التفاضل والتكامل عن إيه هو التفاضل والتكامل؟
    # هيرد عليك بطريقته هو وملخص اللي هيقوله غالباً هيكون حاجة شبه كدة:"
    # ==============================================================
    scene.play(
        FadeIn(person_right),
        FadeIn(person_left),
        run_time=0.8,
    )

    # الاحتفاظ بدورة التنفس الأصلية 1.3 ثانية بالضبط لمنع أي تشوه في العين
    scene.play(
        person_right.breathe(
            amount=0.035,
            run_time=1.3,
        ),
        person_left.breathe(
            amount=0.035,
            run_time=1.3,
        ),
    )

    # وقفة للمعلق لإنهاء جملة التمهيد
    scene.wait(3.5)

    # ==============================================================
    # 5. بالونة السؤال (نفس قيم الأنيميشن الأصلية للكود)
    # ==============================================================
    scene.play(
        FadeIn(
            dots_r,
            scale=0.5,
        ),
        FadeIn(
            box_r,
            scale=0.9,
        ),
        run_time=0.5,
    )

    scene.play(
        LaggedStart(
            *[
                FadeIn(
                    line,
                    shift=LEFT * 0.35,
                )
                for line in text_r
            ],
            lag_ratio=0.55,
        ),
        run_time=1.1,
    )

    # وقفة كافية لاستيعاب وقراءة السؤال
    scene.wait(2.5)

    # ==============================================================
    # 6. بالونة الإجابة (نفس قيم الأنيميشن الأصلية للكود)
    # ==============================================================
    scene.play(
        FadeIn(
            dots_l,
            scale=0.5,
        ),
        FadeIn(
            box_l,
            scale=0.9,
        ),
        run_time=0.5,
    )

    scene.play(
        LaggedStart(
            *[
                FadeIn(
                    line,
                    shift=LEFT * 0.35,
                )
                for line in text_l
            ],
            lag_ratio=0.45,
        ),
        run_time=2.0,
    )

    # وقفة مريحة وكافية لقراءة الأسطر الأربعة للإجابة
    scene.wait(6.5)

    # ==============================================================
    # 7. تفريغ المشهد
    # ==============================================================
    all_objects = VGroup(
        person_right,
        person_left,
        box_r,
        dots_r,
        text_r,
        box_l,
        dots_l,
        text_l,
    )

    scene.play(
        FadeOut(all_objects),
        run_time=0.8,
    )

    # استقرار الغرفة قبل دخول الرسم البياني
    scene.wait(1.5)

    # الحسبة الإجمالية للمشهد الثالث:
    # 0.8 (ظهور الشخصيات) + 1.3 (تنفس أصلي) + 3.5 (تمهيد المعلق)
    # + 0.5 (ظهور صندوق السؤال) + 1.1 (ظهور نص السؤال) + 2.5 (وقفة السؤال)
    # + 0.5 (ظهور صندوق الإجابة) + 2.0 (ظهور نص الإجابة) + 6.5 (قراءة الإجابة)
    # + 0.8 (تفريغ المشهد) + 1.5 (استقرار نهائي)
    # = 22.0 ثانية بالتمام والكمال، مع سلامة العين 100%!